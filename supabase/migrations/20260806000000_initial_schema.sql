drop policy if exists commandes_select on public.commandes;
create policy commandes_select on public.commandes
for select to authenticated
using (
  revendeur_id = auth.uid()
  or cordonnier_id = auth.uid()
  or public.current_user_role() = 'admin'
);

drop policy if exists commandes_insert on public.commandes;
create policy commandes_insert on public.commandes
for insert to authenticated
with check (
  public.is_manager()
  and (revendeur_id = auth.uid() or public.current_user_role() = 'admin')
  and exists (
    select 1 from public.clients
    where id = commandes.client_id and (clients.revendeur_id = auth.uid() or public.current_user_role() = 'admin')
  )
  and exists (
    select 1 from public.profiles
    where id = commandes.cordonnier_id and role = 'cordonnier' and is_active = true
  )
);

