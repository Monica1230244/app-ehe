create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  initial_role text;
begin
  if exists (select 1 from public.profiles where role in ('revendeur', 'admin')) then
    initial_role := 'cordonnier';
  else
    initial_role := 'revendeur';
  end if;

  insert into public.profiles (id, nom, email, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'nom', ''), split_part(new.email, '@', 1)),
    new.email,
    initial_role
  )
  on conflict (id) do update
  set nom = excluded.nom, email = excluded.email;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid() and is_active = true;
$$;

create or replace function public.is_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_user_role() in ('revendeur', 'admin'), false);
$$;

create or replace function public.can_access_commande(p_commande_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.commandes
    where id = p_commande_id
      and (
        revendeur_id = auth.uid()
        or cordonnier_id = auth.uid()
        or public.current_user_role() = 'admin'
      )
  );
$$;

create or replace function public.can_manage_commande(p_commande_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.commandes
    where id = p_commande_id
      and (revendeur_id = auth.uid() or public.current_user_role() = 'admin')
  );
$$;

create or replace function public.set_commande_numero()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.numero_commande is null or new.numero_commande = '' then
    new.numero_commande := 'CMD-' || to_char(current_date, 'YYYYMMDD') || '-' || lpad(nextval('public.commande_numero_seq')::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists set_commande_numero on public.commandes;
create trigger set_commande_numero before insert on public.commandes
for each row execute function public.set_commande_numero();

