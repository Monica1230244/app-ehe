for each row execute function public.add_initial_commande_status();

create or replace function public.change_commande_status(p_commande_id bigint, p_nouveau_statut text)
returns public.commandes
language plpgsql
security definer
set search_path = public
as $$
declare
  current_order public.commandes%rowtype;
  updated_order public.commandes%rowtype;
  current_role text;
  transition_allowed boolean := false;
begin
  if p_nouveau_statut not in ('en_attente', 'en_fabrication', 'prete', 'livree', 'annulee') then
    raise exception 'Statut invalide';
  end if;

  select * into current_order
  from public.commandes
  where id = p_commande_id
  for update;

  if not found then
    raise exception 'Commande introuvable';
  end if;

  current_role := public.current_user_role();

  if current_role = 'cordonnier' then
    if current_order.cordonnier_id is distinct from auth.uid() then
      raise exception 'Cette commande ne vous est pas attribuée';
    end if;
    transition_allowed :=
      (current_order.statut = 'en_attente' and p_nouveau_statut = 'en_fabrication')
      or (current_order.statut = 'en_fabrication' and p_nouveau_statut = 'prete');
  elsif current_role = 'revendeur' then
    if current_order.revendeur_id is distinct from auth.uid() then
      raise exception 'Accès refusé';
    end if;
    transition_allowed :=
      (current_order.statut = 'en_attente' and p_nouveau_statut = 'annulee')
      or (current_order.statut = 'prete' and p_nouveau_statut = 'livree');
  elsif current_role = 'admin' then
    transition_allowed := true;
  else
    raise exception 'Accès refusé';
  end if;

  if not transition_allowed then
    raise exception 'Transition de statut non autorisée';
  end if;

  update public.commandes
  set statut = p_nouveau_statut,
      date_debut_fabrication = case when p_nouveau_statut = 'en_fabrication' then coalesce(date_debut_fabrication, now()) else date_debut_fabrication end,
      date_fin = case when p_nouveau_statut in ('prete', 'livree', 'annulee') then now() else date_fin end
  where id = p_commande_id
  returning * into updated_order;

  insert into public.commande_statuts (commande_id, user_id, statut)
  values (p_commande_id, auth.uid(), p_nouveau_statut);

  if p_nouveau_statut = 'prete' then
    insert into public.notifications (user_id, commande_id, message)
    values (current_order.revendeur_id, p_commande_id, 'La commande ' || current_order.numero_commande || ' est prête.');
  end if;

  return updated_order;
end;
$$;

