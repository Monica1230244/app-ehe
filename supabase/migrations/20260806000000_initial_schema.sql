create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nom text not null,
  email text unique not null,
  role text not null default 'cordonnier' check (role in ('revendeur', 'cordonnier', 'admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  revendeur_id uuid not null default auth.uid() references public.profiles(id) on delete restrict,
  nom text not null,
  telephone text not null,
  email text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create sequence if not exists public.commande_numero_seq;

create table if not exists public.commandes (
  id bigint generated by default as identity primary key,
  numero_commande text unique,
  client_id bigint not null,
  revendeur_id uuid not null default auth.uid(),
  cordonnier_id uuid not null,
  modele text not null,
  pointure text not null,
  couleur text not null,
  matiere text not null,
  semelle text not null,
  quantite integer not null default 1 check (quantite > 0),
  statut text not null default 'en_attente' check (statut in ('en_attente', 'en_fabrication', 'prete', 'livree', 'annulee')),
  date_souhaitee date,
  date_creation timestamptz not null default now(),
  date_debut_fabrication timestamptz,
  date_fin timestamptz,
  observations text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint commandes_client_id_fkey foreign key (client_id) references public.clients(id) on delete restrict,
  constraint commandes_revendeur_id_fkey foreign key (revendeur_id) references public.profiles(id) on delete restrict,
  constraint commandes_cordonnier_id_fkey foreign key (cordonnier_id) references public.profiles(id) on delete restrict
);

create table if not exists public.photos (
  id bigint generated by default as identity primary key,
  commande_id bigint not null references public.commandes(id) on delete cascade,
  type_photo text not null check (type_photo in ('modele', 'pied_gauche', 'pied_droit', 'autre')),
  storage_path text not null,
  file_name text not null,
  created_at timestamptz not null default now(),
  unique (commande_id, type_photo)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  commande_id bigint references public.commandes(id) on delete cascade,
  message text not null,
  lu boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.commande_statuts (
  id bigint generated by default as identity primary key,
  commande_id bigint not null references public.commandes(id) on delete cascade,
  user_id uuid,
  statut text not null check (statut in ('en_attente', 'en_fabrication', 'prete', 'livree', 'annulee')),
  commentaire text,
  created_at timestamptz not null default now(),
  constraint commande_statuts_user_id_fkey foreign key (user_id) references public.profiles(id) on delete set null
);

create index if not exists idx_clients_revendeur_id on public.clients(revendeur_id);
create index if not exists idx_commandes_client_id on public.commandes(client_id);
create index if not exists idx_commandes_revendeur_id on public.commandes(revendeur_id);
create index if not exists idx_commandes_cordonnier_id on public.commandes(cordonnier_id);
create index if not exists idx_commandes_statut on public.commandes(statut);
create index if not exists idx_photos_commande_id on public.photos(commande_id);
create index if not exists idx_notifications_user_id on public.notifications(user_id);
create index if not exists idx_notifications_lu on public.notifications(lu);
