drop policy if exists modele_photos_select on storage.objects;
create policy modele_photos_select on storage.objects
for select to authenticated
using (
  bucket_id = 'modele-photos'
  and public.can_access_modele_photo(name)
);

drop policy if exists modele_photos_insert on storage.objects;
create policy modele_photos_insert on storage.objects
for insert to authenticated
with check (
  bucket_id = 'modele-photos'
  and public.is_manager()
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists modele_photos_delete on storage.objects;
create policy modele_photos_delete on storage.objects
for delete to authenticated
using (
  bucket_id = 'modele-photos'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.current_user_role() = 'admin'
  )
);
