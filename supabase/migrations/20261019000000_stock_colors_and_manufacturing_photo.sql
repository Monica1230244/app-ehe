create sequence if not exists public.modele_stock_reference_seq;

do $$
declare
  current_max bigint;
  missing_model record;
begin
  select coalesce(max((substring(reference from '^EHE-([0-9]+)$'))::bigint), 0)
  into current_max
  from public.modeles_stock;

  if current_max > 0 then
    perform setval('public.modele_stock_reference_seq', current_max, true);
  end if;

  for missing_model in
    select id
    from public.modeles_stock
    where nullif(btrim(reference), '') is null
    order by created_at, id
  loop
    update public.modeles_stock
    set reference = 'EHE-' || lpad(nextval('public.modele_stock_reference_seq')::text, 3, '0')
    where id = missing_model.id;
  end loop;
end;
$$;

create or replace function public.set_modele_stock_reference()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if nullif(btrim(new.reference), '') is null then
    loop
      new.reference := 'EHE-' || lpad(nextval('public.modele_stock_reference_seq')::text, 3, '0');
      exit when not exists (
        select 1
        from public.modeles_stock
        where revendeur_id = new.revendeur_id
          and lower(reference) = lower(new.reference)
      );
    end loop;
  else
    new.reference := btrim(new.reference);
  end if;

  return new;
end;
$$;

drop trigger if exists set_modele_stock_reference on public.modeles_stock;
create trigger set_modele_stock_reference
before insert on public.modeles_stock
for each row execute function public.set_modele_stock_reference();

create table if not exists public.modele_stock_couleurs (
  id bigint generated by default as identity primary key,
  modele_stock_id bigint not null references public.modeles_stock(id) on delete cascade,
  couleur text not null check (char_length(btrim(couleur)) between 1 and 80),
  position integer not null default 1 check (position > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists idx_modele_stock_couleurs_unique
on public.modele_stock_couleurs(modele_stock_id, lower(btrim(couleur)));

create index if not exists idx_modele_stock_couleurs_model
on public.modele_stock_couleurs(modele_stock_id, position);

