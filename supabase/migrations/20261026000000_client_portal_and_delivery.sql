create table if not exists public.client_commande_livraisons (
  id bigint generated by default as identity primary key,
  commande_id bigint not null unique references public.commandes(id) on delete cascade,
  client_id bigint not null references public.clients(id) on delete cascade,
  nom_reception text not null check (char_length(btrim(nom_reception)) between 2 and 120),
  telephone text not null check (char_length(btrim(telephone)) between 6 and 30),
  adresse text not null check (char_length(btrim(adresse)) between 5 and 240),
  ville text not null check (char_length(btrim(ville)) between 2 and 100),
  instructions text check (instructions is null or char_length(instructions) <= 1000),
  statut text not null default 'recue' check (statut in ('recue', 'confirmee', 'livree')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_client_commande_livraisons_client
on public.client_commande_livraisons(client_id);

drop trigger if exists client_commande_livraisons_updated_at on public.client_commande_livraisons;
create trigger client_commande_livraisons_updated_at
before update on public.client_commande_livraisons
for each row execute function public.update_updated_at();

alter table public.client_commande_livraisons enable row level security;

drop policy if exists client_commande_livraisons_select on public.client_commande_livraisons;
create policy client_commande_livraisons_select on public.client_commande_livraisons
for select to authenticated
using (public.can_access_commande(commande_id));

drop policy if exists client_commande_livraisons_update on public.client_commande_livraisons;
create policy client_commande_livraisons_update on public.client_commande_livraisons
for update to authenticated
using (public.can_access_commande(commande_id))
with check (public.can_access_commande(commande_id));

grant select, update on public.client_commande_livraisons to authenticated;

create or replace function public.get_client_portal(p_client_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
with client_row as (
  select
    id as client_id,
    revendeur_id,
    civilite,
    nom,
    telephone,
    catalogue_token_expires_at
  from public.clients
  where catalogue_token = p_client_token
    and catalogue_token_expires_at > now()
),
order_rows as (
  select
    commande.id,
    commande.created_at,
    jsonb_build_object(
      'id', commande.id,
      'numero_commande', commande.numero_commande,
      'statut', commande.statut,
      'date_creation', commande.date_creation,
      'date_souhaitee', commande.date_souhaitee,
      'date_debut_fabrication', commande.date_debut_fabrication,
      'date_fin', commande.date_fin,
      'observations', commande.observations,
      'articles', coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', article.id,
            'modele', article.modele,
            'pointure', article.pointure,
            'couleur', article.couleur,
            'quantite', article.quantite,
            'position', article.position
          )
          order by article.position
        )
        from public.commande_articles article
        where article.commande_id = commande.id
      ), '[]'::jsonb),
      'livraison', case
        when livraison.id is null then null
        else jsonb_build_object(
          'nom_reception', livraison.nom_reception,
          'telephone', livraison.telephone,
          'adresse', livraison.adresse,
          'ville', livraison.ville,
          'instructions', livraison.instructions,
          'statut', livraison.statut,
          'updated_at', livraison.updated_at
        )
      end
    ) as payload
  from public.commandes commande
  join client_row client on client.client_id = commande.client_id
  left join public.client_commande_livraisons livraison on livraison.commande_id = commande.id
),
selection_rows as (
  select
    demande.id,
    demande.created_at,
    jsonb_build_object(
      'id', demande.id,
      'statut', demande.statut,
      'created_at', demande.created_at,
      'articles', coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'modele', modele.nom,
            'reference', modele.reference,
            'quantite', article.quantite,
            'pointure', article.pointure,
            'couleur', article.couleur
          )
          order by article.position
        )
        from public.demande_catalogue_articles article
        join public.modeles_stock modele on modele.id = article.modele_stock_id
        where article.demande_id = demande.id
      ), '[]'::jsonb)
    ) as payload
  from public.demandes_catalogue demande
  join client_row client on client.client_id = demande.client_id
)
select jsonb_build_object(
  'client', jsonb_build_object(
    'civilite', client.civilite,
    'nom', client.nom,
    'telephone', client.telephone,
    'expires_at', client.catalogue_token_expires_at
  ),
  'commandes', coalesce((
    select jsonb_agg(payload order by created_at desc)
    from order_rows
  ), '[]'::jsonb),
  'selections', coalesce((
    select jsonb_agg(payload order by created_at desc)
    from selection_rows
  ), '[]'::jsonb)
)
from client_row client;
$$;

create or replace function public.save_client_delivery(
  p_client_token uuid,
  p_commande_id bigint,
  p_nom_reception text,
  p_telephone text,
  p_adresse text,
  p_ville text,
  p_instructions text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  client_id_value bigint;
  owner_id uuid;
  order_number text;
  saved_delivery public.client_commande_livraisons%rowtype;
begin
  select id into client_id_value
  from public.clients
  where catalogue_token = p_client_token
    and catalogue_token_expires_at > now();

  if client_id_value is null then
    raise exception 'Ce lien client est invalide ou expiré';
  end if;

  select revendeur_id, numero_commande
  into owner_id, order_number
  from public.commandes
  where id = p_commande_id
    and client_id = client_id_value
    and statut = 'prete';

  if owner_id is null then
    raise exception 'Cette commande ne peut pas encore recevoir une livraison';
  end if;

  if char_length(btrim(coalesce(p_nom_reception, ''))) < 2
    or char_length(btrim(coalesce(p_telephone, ''))) < 6
    or char_length(btrim(coalesce(p_adresse, ''))) < 5
    or char_length(btrim(coalesce(p_ville, ''))) < 2 then
    raise exception 'Tous les champs de livraison obligatoires doivent être remplis';
  end if;

  if char_length(coalesce(p_instructions, '')) > 1000 then
    raise exception 'Les instructions de livraison sont trop longues';
  end if;

  insert into public.client_commande_livraisons (
    commande_id,
    client_id,
    nom_reception,
    telephone,
    adresse,
    ville,
    instructions
  ) values (
    p_commande_id,
    client_id_value,
    btrim(p_nom_reception),
    btrim(p_telephone),
    btrim(p_adresse),
    btrim(p_ville),
    nullif(btrim(coalesce(p_instructions, '')), '')
  )
  on conflict (commande_id) do update set
    client_id = excluded.client_id,
    nom_reception = excluded.nom_reception,
    telephone = excluded.telephone,
    adresse = excluded.adresse,
    ville = excluded.ville,
    instructions = excluded.instructions,
    statut = 'recue',
    updated_at = now()
  returning * into saved_delivery;

  insert into public.notifications (user_id, commande_id, message)
  values (
    owner_id,
    p_commande_id,
    'Le client a envoyé ses informations de livraison pour la commande ' || coalesce(order_number, '#' || p_commande_id) || '.'
  );

  return jsonb_build_object(
    'ok', true,
    'commande_id', saved_delivery.commande_id,
    'statut', saved_delivery.statut,
    'updated_at', saved_delivery.updated_at
  );
end;
$$;

revoke execute on function public.get_client_portal(uuid) from public;
grant execute on function public.get_client_portal(uuid) to anon, authenticated;

revoke execute on function public.save_client_delivery(uuid, bigint, text, text, text, text, text) from public;
grant execute on function public.save_client_delivery(uuid, bigint, text, text, text, text, text) to anon, authenticated;
